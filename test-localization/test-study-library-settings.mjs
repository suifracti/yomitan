import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM} from 'jsdom';

const flush = () => new Promise((resolve) => setImmediate(resolve));

test('save/review panel edits targets, checks readonly, and creates only on separate explicit clicks', async () => {
    const dom = new JSDOM(readFileSync(new URL('../ext/study-settings.html', import.meta.url), 'utf8'), {url: 'https://extension.test/study-settings.html'});
    globalThis.document = dom.window.document;
    let settings = {ankiEnabled: true, targetId: 'old', vault: '/old/vault', directory: '学习/语境', deck: 'Missing deck', model: '外语语境卡'};
    const calls = [];
    let saveAvailable = true;
    globalThis.chrome = {permissions: {contains: async () => true, request: async () => true}, storage: {onChanged: {addListener() {}}}, runtime: {sendMessage: async ({studyAction, data}) => {
        calls.push({action: studyAction, data});
        let value;
        if (studyAction === 'settings') value = {model: 'gpt-6.1-sol', effort: 'low', cacheEnabled: true};
        else if (studyAction === 'saved') value = [];
        else if (studyAction === 'librarySettingsGet') value = settings;
        else if (studyAction === 'librarySettingsSave') value = settings = {...data.settings, targetId: 'changed'};
        else if (studyAction === 'librarySettingsCheck') value = {...settings, decks: ['Existing deck'], models: [], status: {vaultExists: true, directoryExists: false, saveAvailable, saveMessage: saveAvailable ? '' : '目录不可写', ankiConnected: true, deckExists: false, modelExists: false, modelCompatible: false, missing: ['deck', 'model']}};
        else if (studyAction === 'librarySettingsPrepare') value = {...settings, message: '准备完成'};
        else if (studyAction === 'librarySettingsOpen') value = {...settings, message: '目录已打开'};
        else throw new Error(`Unexpected action: ${studyAction}`);
        return {ok: true, value};
    }}};
    await import('../ext/js/pages/study-settings-main.js');
    await flush();
    const $ = (selector) => document.querySelector(selector);
    assert.ok($('#library-settings-form'), 'save/review form is present');
    assert.equal($('#library-vault').value, settings.vault);
    assert.equal($('#library-directory').value, settings.directory);
    assert.equal($('#library-model').readOnly, true);
    assert.ok(calls.every(({action}) => ['settings', 'saved', 'librarySettingsGet'].includes(action)), 'startup reads local/native settings only; no check, model request or creation');
    $('#library-check').click(); await flush();
    assert.match($('#library-check-result').textContent, /Missing deck/);
    assert.match($('#library-check-result').textContent, /缺失/);
    assert.match($('#library-check-result').textContent, /首次保存/);
    assert.match($('#library-check-result').textContent, /可保存/);
    assert.ok([...$('#library-deck').options].some((option) => option.value === 'Existing deck'));
    assert.equal($('#library-deck').value, 'Missing deck', 'missing saved target must not silently select a different deck');
    $('#library-vault').value = '/new/vault';
    $('#library-open').click(); await flush();
    assert.equal(calls.filter(({action}) => action === 'librarySettingsOpen').length, 0, 'dirty targets must be saved before opening/preparing');
    assert.match($('#library-status').textContent, /先保存/);
    $('#library-deck').value = '__new_deck__';
    $('#library-deck').dispatchEvent(new dom.window.Event('change'));
    $('#library-new-deck').value = 'My new deck';
    $('#library-anki-enabled').checked = false;
    $('#library-settings-form').dispatchEvent(new dom.window.Event('submit', {cancelable: true})); await flush();
    assert.deepEqual(calls.find(({action}) => action === 'librarySettingsSave').data, {settings: {vault: '/new/vault', directory: '学习/语境', ankiEnabled: false, deck: 'My new deck', model: '外语语境卡'}});
    assert.equal(calls.filter(({action}) => action === 'librarySettingsPrepare').length, 0, 'saving does not create decks, models or notes');
    $('#library-create-deck').click(); await flush();
    $('#library-create-model').click(); await flush();
    assert.deepEqual(calls.filter(({action}) => action === 'librarySettingsPrepare').map(({data}) => data), [{createDeck: true, createModel: false}, {createDeck: false, createModel: true}]);
    $('#library-open').click(); await flush();
    assert.equal(calls.filter(({action}) => action === 'librarySettingsOpen').length, 1);
    saveAvailable = false;
    $('#library-check').click(); await flush();
    assert.match($('#library-check-result').textContent, /保存目标：不可用/);
    assert.match($('#library-check-result').textContent, /目录不可写/);
    assert.equal($('#library-advanced').getAttribute('href'), '/settings.html#!anki');
    assert.ok($('#model') && $('#cacheEnabled') && $('#saved'), 'existing settings and favorites remain');
    dom.window.close();
});
