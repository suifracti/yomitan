// @vitest-environment jsdom
import {test, expect, vi} from 'vitest';
import {readFileSync} from 'node:fs';
vi.mock('../ext/js/display/study-workspace.js', () => ({prepareStudyWorkspace: () => ({dispose() {}})}));
import {prepareStudyDictionary} from '../ext/js/display/study-dictionary.js';
import {prepareStudyFocus} from '../ext/js/display/study-focus.js';
test('dictionary orders definitions before collapsed references, shows one example and labels POS pages in Chinese', () => {
    document.documentElement.removeAttribute('data-study-focus-ready');
    document.body.innerHTML = readFileSync(`${import.meta.dirname}/fixtures/study-focus.html`, 'utf8').split('<script type="module">')[0];
    globalThis.ResizeObserver = class {observe() {} disconnect() {}};
    globalThis.chrome = {runtime: {sendMessage: async () => ({ok: true, value: {cached: false}})}};
    const entry = document.querySelector('.study-entry');
    const senses = [...entry.querySelectorAll('[data-sc-content=glosses]>li')];
    senses.forEach((row, i) => row.insertAdjacentHTML('afterbegin', `<span data-sc-category="partOfSpeech">${i < 2 ? 'pron' : 'n'}</span> `));
    senses[0].insertAdjacentHTML('afterbegin', '<span data-sc-category="register">col</span><span data-sc-category="type">indef</span>');
    const examples = senses[0].querySelector('details');
    examples.insertAdjacentHTML('beforeend', '<div data-sc-content="extra-info">Another example.</div><div data-sc-content="extra-info">Last example.</div>');
    const disposeDictionary = prepareStudyDictionary(entry, 'ability');
    const handlers = new Map();
    const display = {query: 'ability', history: {state: {sentence: {text: 'This is ability.'}}}, on: (name, fn) => handlers.set(name, fn)};
    prepareStudyFocus(display, {call: async () => ({items: [], anki: {items: []}})});
    handlers.get('contentUpdateComplete')();
    const scroll = document.querySelector('.sf-dictionary-scroll');
    const definitions = scroll.querySelector('.study-dictionary-details');
    const forms = scroll.querySelector('.sf-dictionary-forms');
    expect(definitions.compareDocumentPosition(forms) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
    expect(forms.querySelector('details').open).toBe(false);
    expect(forms.querySelector('.sf-reference-summary').textContent).toContain('abilities');
    expect(scroll.querySelector('.sf-dictionary-info details').open).toBe(false);
    expect(document.querySelector('.study-sense-count').textContent).toBe('代词 · 1/2');
    expect(senses[0].textContent).toContain('口语不定代词');
    const extra = examples.querySelectorAll('[data-sc-content=extra-info]');
    expect(extra[0].hidden).toBe(false); expect(extra[1].hidden).toBe(true);
    expect(examples.querySelector('button').textContent).toBe('另 2 个例句');
    examples.querySelector('button').click(); expect(extra[1].hidden).toBe(false);
    document.querySelector('[data-study-dictionary-next]').click();
    expect(document.querySelector('.study-sense-count').textContent).toBe('名词 · 2/2');
    handlers.get('contentClear')(); disposeDictionary();
});
